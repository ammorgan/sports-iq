import type { Challenge, LearningModule } from "./learning-data";

export type FootballGamePathNodeKind =
  | "film"
  | "audio"
  | "field-read"
  | "match"
  | "scenario"
  | "review"
  | "checkpoint"
  | "boss";

export type FootballGamePathNode = {
  id: string;
  kind: FootballGamePathNodeKind;
  title: string;
  summary: string;
  sourceIds: string[];
  module: LearningModule;
};

export type FootballGamePath = {
  id: string;
  sportId: "football";
  pathway: "general" | "position";
  position?: "Quarterback";
  title: string;
  summary: string;
  nodes: FootballGamePathNode[];
};

const GENERAL_SOURCE_IDS = ["nfl-2025-rules"];
const TEAM_SOURCE_IDS = ["nfl-2025-rules", "nfl-football-terms"];

function generalModule(
  id: string,
  level: number,
  title: string,
  description: string,
  challenges: Challenge[],
  sourceIds = GENERAL_SOURCE_IDS,
): LearningModule {
  return {
    id,
    sportId: "football",
    level,
    pathway: "general",
    title,
    description,
    estimatedMinutes: 6,
    challenges,
    sourceIds: [...sourceIds],
  };
}

